"""Generates worlds/pasture.sdf from fence.json (fence, faults, trees, herd, X500 drone).

Two looks (fence.json "look", or GARDIAN_LOOK):
- "rich" (default): sky, a low afternoon sun, textured grass, rolling hills around the farm, more and varied trees,
  a farmyard (barn, silo, hay, house) and rounder animals. The paddock itself stays perfectly flat, because the flight,
  the physics and the alert projection assume flat ground there.
- "classic": the original flat green world. tools/make_dataset.py uses it, so the detector's training data stays
  reproducible.
"""
